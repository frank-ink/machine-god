    raw_json = json.dumps(raw, ensure_ascii=False, sort_keys=True, default=str)
    timestamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    return {
        "id": str(uuid.uuid4()),
        "component": component,
        "source": source,
        "line_hash": hashlib.sha256(f"{component}|{metric}|{timestamp}|{raw_json}".encode("utf-8")).hexdigest()[:16],
        "metric": metric,
        "value": float(value),
        "unit": unit,
        "time": timestamp,
        "host": "local",
        "instance": USER_ID,
        "raw": raw_json,
    }


