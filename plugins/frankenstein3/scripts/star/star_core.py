        with contextlib.closing(write_connection()) as c:
            for z in all_lines:
                c.execute(
                    "INSERT INTO measurement (id, component, source, line_hash, metric, value, unit, "
                    "time, host, instance, raw) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                    (z["id"], z["component"], z["source"], z["line_hash"], z["was"], z["value"],
                     z["unit"], z["time"], z["host"], z["instance"], z["raw"]),
                )
