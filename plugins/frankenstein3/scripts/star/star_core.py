_MEASUREMENT_DURATION_RE = re.compile(r"duration event=(\S+) (\d+)ms")


def _instrument_hook_latency() -> list:
    source = "hook.log (star_cli.py:_log 'duration event=...')"
    try:
        text = LOG.read_text(encoding="utf-8", errors="replace")
    except Exception as e:
        return [_measurement_line("hook_latency", source, "read_error", 0.0, "bool",
                                _measurement_unknown(f"{type(e).__name__}: {e}"))]

    per_event: dict = {}
    for line in text.splitlines():
        m = _MEASUREMENT_DURATION_RE.search(line)
        if m:
            per_event.setdefault(m.group(1), []).append(int(m.group(2)))

    if not per_event:
        return [_measurement_line("hook_latency", source, "none_duration_lines", 0.0, "bool",
                                _measurement_unknown("hook.log contains no 'duration event=' lines"))]

    k = _config()
    limits = {
        "SessionStart": k["limit.SessionStart"], "PreToolUse": k["limit.PreToolUse"],
        "PostToolUse": k["limit.PostToolUse"],
        "Stop": k["limit.Stop"], "SessionEnd": k["limit.SessionEnd"],
        "UserPromptSubmit": k["limit.UserPromptSubmit"],
    }
    standard_limit = k["limit.standard"]

    lines = []
    for event, values in sorted(per_event.items()):
        values_sorted = sorted(values)
        n = len(values_sorted)
        p50 = values_sorted[int(0.50 * (n - 1))]
        p95 = values_sorted[int(0.95 * (n - 1))]
        maxi = values_sorted[-1]
        budget_s = limits.get(event, standard_limit)
        budget_ms = budget_s * 1000 if budget_s is not None else None
        lines.append(_measurement_line(
            "hook_latency", source, f"latency:{event}", float(p50), "ms",
            {
                "event": event, "n": n, "p50_ms": p50, "p95_ms": p95, "max_ms": maxi,
                "budget_ms": budget_ms,
                "under_budget": (maxi <= budget_ms) if budget_ms is not None else None,
            },
        ))
    return lines


