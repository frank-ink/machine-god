# ── Evidence check (ZECP14 core): mechanical, never model-formulated ───────
_EVIDENCE_EFFECT_RE = re.compile(r"^(?:effect:)?(eff-[a-zA-Z0-9._-]+)$")


_EVIDENCE_FILE_RE = re.compile(r"^file:(.+):([0-9a-fA-F]{64})$")


_EVIDENCE_TEST_RE = re.compile(r"^test:([^:]+)(?::(.*))?$")


def _evidence_check(c, session: Optional[str], evidence: Optional[str]) -> dict:
    """Returns {'ok':bool, 'kind':str, 'detail':str}. Three permissible
    evidence forms (see Task 5b): an effect_id FROM THIS SESSION, a
    file path with sha256, or a test result. Everything else -- including
    empty evidence -- is NOT evidence, no matter how plausible the text sounds.

    Deviation/Honesty: the full ZECP17 effect contract (status
    ALLOWED/VERIFIED/REJECTED/UNCHECKED, requested_generation real) is
    Phase 2 and had NOT landed at the time of this build -- effects.status
    only had 'executed'/'error' at measurement time. The check here
    therefore does NOT require status='VERIFIED' (that wouldn't exist yet),
    but only: the row really exists, provably belongs to the specified session
    (via episode_id -> workspace_episodes.session_id), and is not itself
    booked as 'error'. Once P2 lands, the same query automatically becomes
    stricter (status will then be e.g. 'VERIFIED') -- no rework needed here,
    just a formulation that already fits both contracts (comparison is != 'error', not == 'executed')."""
    if not evidence or not evidence.strip():
        return {"ok": False, "kind": "none_evidence", "detail": "no evidence specified"}
    evidence = evidence.strip()

    m = _EVIDENCE_EFFECT_RE.match(evidence)
    if m:
        eff_id = m.group(1)
        row = c.execute(
            "SELECT e.status, e.ts, w.session_id FROM effects e "
            "LEFT JOIN workspace_episodes w ON e.episode_id = w.episode_id "
            "WHERE e.effect_id=?",
            (eff_id,),
        ).fetchone()
        if not row:
            return {"ok": False, "kind": "effect_id", "detail": f"effect_id {eff_id} not found in effects"}
        status, ts, eff_session = row
        if session and eff_session and eff_session != session:
            return {"ok": False, "kind": "effect_id",
                     "detail": f"effect_id {eff_id} belongs to session {eff_session}, not to {session}"}
        if status == "error":
            return {"ok": False, "kind": "effect_id", "detail": f"effect_id {eff_id} itself recorded as 'error'"}
        return {"ok": True, "kind": "effect_id", "detail": f"effect_id={eff_id} status={status} ts={ts}"}

    m = _EVIDENCE_FILE_RE.match(evidence)
    if m:
        path, expected = m.group(1), m.group(2).lower()
        if not os.path.isfile(path):
            return {"ok": False, "kind": "file_sha256", "detail": f"File not found: {path}"}
        try:
            real = hashlib.sha256(Path(path).read_bytes()).hexdigest()
        except Exception as e:
            return {"ok": False, "kind": "file_sha256", "detail": f"sha256 failed: {e}"}
        if real != expected:
            return {"ok": False, "kind": "file_sha256",
                     "detail": f"sha256 mismatch: expected {expected}, actual {real}"}
        return {"ok": True, "kind": "file_sha256", "detail": f"{path} sha256={real}"}

    m = _EVIDENCE_TEST_RE.match(evidence)
    if m:
        exit_code = m.group(1).strip()
        description = (m.group(2) or "").strip()
        if exit_code != "0":
            return {"ok": False, "kind": "test_exit",
                     "detail": f"Test result exit_code={exit_code} (not 0) -- {description}"}
        return {"ok": True, "kind": "test_exit", "detail": f"exit_code=0 {description}"}

    return {"ok": False, "kind": "unknown_format",
             "detail": "Evidence must be effect:<eff-id>, file:<path>:<sha256> or "
                        "test:<exit_code>:<description>"}


def reconcile(work_package_id: str, result: str, evidence: Optional[str], session_id: Optional[str] = None,
              topic: str = "") -> dict:
    """ZECP14: closes a package -- BUT ONLY if the evidence mechanically
    checks out. This is the actual acceptance test of Phase 5 (Task,
    Check Step 2): reconcile WITHOUT valid evidence sets stand='failed'
    and marks result as 'unsubstantiated_claim' -- is NEVER booked as
    success, regardless of what --result claims.

    `topic` (optional, 2026-08-27 addendum): as in handoff() -- if missing,
    first checks whether THIS work_package_id already has a topics_status row
    (which handoff() would have written on creation, with or without
    explicit --topic) and continues using its `topic` unchanged, so that
    reconcile() closes THE SAME row instead of creating a second one under
    a different key. If none exists (e.g. package came via
    work-package-create instead of handoff), it falls back to the `task`
    of the package."""
    try:
        with contextlib.closing(write_connection()) as c:
            row = c.execute(
                "SELECT session_id, stand, task FROM entityos_work_package WHERE work_package_id=?",
                (work_package_id,),
            ).fetchone()
            if not row:
                return {"work_package_id": work_package_id, "stand": "ERROR", "reason": "work_package_id not found"}
            work_package_session, previous_stand, work_package_task = row
            check_session = session_id or work_package_session

            # 2026-08-27-Addendum (Topics-Register): if handoff() this
            # Package created with an EXPLICIT --topic, MUST reconcile()
            # without own --topic hit the same topics_status row, not
            # a second one under the (different!) task fallback key
            # create -- otherwise the handoff row remains forever on
            # stand='running' are recorded, even though the package has long been finished
            # (exactly the error that the verification run of this build
            # uncovered). Look up via work_package_id, the
            # _topics_status_write() co-stores on every write --
            # no second assignment path, same table.
            previous_topic = None
            try:
                vr = c.execute(
                    "SELECT topic FROM topics_status WHERE work_package_id=? ORDER BY updated DESC LIMIT 1",
                    (work_package_id,),
                ).fetchone()
                previous_topic = vr[0] if vr else None
            except sqlite3.OperationalError:
                pass  # Table not yet created

            finding = _evidence_check(c, check_session, evidence)
            now = _now()

            if finding["ok"]:
                new_stand = "finished"
                stored_result = result
            else:
                new_stand = "failed"
                stored_result = f"unproven_claim: {result or ''}".strip()

            evidence_json = json.dumps({
                "raw": evidence, "kind": finding["kind"], "ok": finding["ok"],
                "reason": finding["detail"], "checked_at": now,
            }, ensure_ascii=False)

            c.execute(
                "UPDATE entityos_work_package SET stand=?, result=?, evidence=?, "
                "changed=? WHERE work_package_id=?",
                (new_stand, stored_result, evidence_json, now, work_package_id),
            )
            c.commit()
    except Exception as e:
        _log(f"reconcile error work_package_id={work_package_id}: {e}")
        return {"work_package_id": work_package_id, "stand": "ERROR", "reason": str(e)}

    _room_call_write(
        check_session or "unknown",
        "COMPLETE" if finding["ok"] else "INVALIDATE",
        f"work_package_id={work_package_id} stand={new_stand} evidence_kind={finding['kind']}",
    )
    _topics_status_write(topic or previous_topic or work_package_task, stored_result,
                              new_stand, work_package_id, check_session)
    return {
        "work_package_id": work_package_id, "stand": new_stand, "result": stored_result,
        "evidence_checked": finding,
    }


