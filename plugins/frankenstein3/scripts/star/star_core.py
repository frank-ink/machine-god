_CONFIG_CACHE: Optional[dict] = None


def _config_parse(value: str, value_type: str, fallback):
    try:
        if value_type == "float":
            return float(value)
        if value_type == "int":
            return int(value)
        if value_type == "bool":
            return value.strip().lower() in ("1", "true", "yes", "wahr", "ja")
        if value_type == "json":
            return json.loads(value)
        return value  # "str"
    except Exception:
        return fallback


def _config() -> dict:
    """One cache per process (module-global) -- no caller should have to worry about
    caching. Missing lines: use fallback value AND (best effort) add them, so that the next change
    finds a place in the DB instead of having to be searched for in the code."""
    global _CONFIG_CACHE
    if _CONFIG_CACHE is not None:
        return _CONFIG_CACHE
    result = {k: v[0] for k, v in _CONFIG_DEFAULTS.items()}
    missing = []
    try:
        with contextlib.closing(connection()) as c:
            available = {
                row[0]: (row[1], row[2])
                for row in c.execute("SELECT key, value, type FROM star_config")
            }
        for key, (fallback, value_type) in _CONFIG_DEFAULTS.items():
            if key in available:
                raw, stored_type = available[key]
                result[key] = _config_parse(raw, stored_type or value_type, fallback)
            else:
                missing.append(key)
    except Exception as e:
        _log(f"config read error, fall back to defaults: {e}")
        missing = []

    if missing:
        try:
            with contextlib.closing(write_connection()) as c:
                now = _now()
                for key in missing:
                    fallback, value_type = _CONFIG_DEFAULTS[key]
                    raw = json.dumps(fallback, ensure_ascii=False) if value_type == "json" else str(fallback)
                    c.execute(
                        "INSERT OR IGNORE INTO star_config (key, value, type, source, changed) "
                        "VALUES (?,?,?,?,?)",
                        (key, raw, value_type, "code-fallback_value", now),
                    )
                c.commit()
        except Exception as e:
            _log(f"config append error: {e}")

    _CONFIG_CACHE = result
    return result


