def _topic_key(topic: str) -> str:
    """Normalized dedup short form: lowercase, whitespace collapsed,
    capped at 80 chars -- the same text (e.g. same `task`) yields
    the same key in handoff() and reconcile(), WITHOUT needing a second
    work_package_id->topic mapping table."""
    return re.sub(r"\s+", " ", (topic or "").strip().lower())[:80]


def _topics_status_write(topic: str, status_text: str, stand: str,
                              work_package_id: Optional[str], session_id: Optional[str]) -> None:
    """Upsert: ONE row per topic, always the latest state. Fail-silent
    like everywhere in this house."""
    topic = (topic or "").strip()
    if not topic:
        return
    key = _topic_key(topic)
    if not key:
        return
    try:
        with contextlib.closing(write_connection()) as c:
            _ensure_topics_status_table(c)
            c.execute(
                "INSERT INTO topics_status (topic_key, topic, status_text, stand, work_package_id, "
                "session_id, updated) VALUES (?,?,?,?,?,?,?) "
                "ON CONFLICT(topic_key) DO UPDATE SET topic=excluded.topic, "
                "status_text=excluded.status_text, stand=excluded.stand, "
                "work_package_id=excluded.work_package_id, session_id=excluded.session_id, "
                "updated=excluded.updated",
                (key, _short(topic, 120), _short(status_text, 400), stand,
                 work_package_id, session_id, _now()),
            )
            c.commit()
    except Exception as e:
        _log(f"topics_status_write error topic={topic!r}: {e}")


def topics_status_search(concept: Optional[str] = None, limit: int = 8) -> list:
    """Manual/programmatic query (`star_cli.py topic-status`) -- the same
    table that automatic_recall()/start_display() also read, just without
    keyword breakdown: ONE term (or none = all), newest first."""
    lines = []
    try:
        with contextlib.closing(connection()) as c:
            if concept and concept.strip():
                like = f"%{concept.strip()}%"
                cur = c.execute(
                    "SELECT topic, status_text, stand, updated, session_id FROM topics_status "
                    "WHERE topic LIKE ? OR status_text LIKE ? ORDER BY updated DESC LIMIT ?",
                    (like, like, limit),
                )
            else:
                cur = c.execute(
                    "SELECT topic, status_text, stand, updated, session_id FROM topics_status "
                    "ORDER BY updated DESC LIMIT ?", (limit,),
                )
            for topic, status_text, stand, updated, session_id in cur:
                lines.append({"topic": topic, "status_text": status_text, "stand": stand,
                                "updated": updated, "session_id": session_id})
    except sqlite3.OperationalError:
        pass  # Table does not exist yet -- before first handoff/reconcile with --topic normal
    except Exception as e:
        _log(f"topics_status_search error concept={concept!r}: {e}")
    return lines


