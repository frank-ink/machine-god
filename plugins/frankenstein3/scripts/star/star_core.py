BUSY_MS = 30000


ATTEMPTS = 4


BACKOFF_S = 0.15


def _connect(path: str = DB_PATH) -> sqlite3.Connection:
    """Read-only connection with busy_timeout and retry."""
    last = None
    for attempt in range(ATTEMPTS):
        try:
            c = sqlite3.connect("file:%s?mode=ro" % path, uri=True, timeout=BUSY_MS / 1000.0)
            c.execute("PRAGMA busy_timeout=%d" % BUSY_MS)
            c.execute("PRAGMA query_only=ON")
            return c
        except sqlite3.Error as e:
            last = e
            time.sleep(BACKOFF_S * (2 ** attempt))
    raise last  # type: ignore[misc]


def connection(path: Optional[str] = None) -> sqlite3.Connection:
    """The house's read-only default connection. `path=None` (default)
    re-reads the module-global DB_PATH on EVERY call instead of using a
    default bound at import time -- PHASE 19: the
    self-healing (_db_self_healing_ensure()) can reset DB_PATH within
    A SINGLE hook process run (pointer/fallback search/snapshot/
    fresh DB), and all callers further down in the same run must see that
    immediately, not the path from before the healing."""
    return _connect(path if path is not None else DB_PATH)


def _connect_writing(path: str = DB_PATH) -> sqlite3.Connection:
    last = None
    for attempt in range(ATTEMPTS):
        try:
            c = sqlite3.connect("file:%s?mode=rw" % path, uri=True, timeout=BUSY_MS / 1000.0)
            c.execute("PRAGMA busy_timeout=%d" % BUSY_MS)
            return c
        except sqlite3.Error as e:
            last = e
            time.sleep(BACKOFF_S * (2 ** attempt))
    raise last  # type: ignore[misc]


def write_connection(path: Optional[str] = None) -> sqlite3.Connection:
    """The house's write default connection. Same reasoning
    for `path=None` as in connection() above (PHASE 19-self-healing)."""
    return _connect_writing(path if path is not None else DB_PATH)


