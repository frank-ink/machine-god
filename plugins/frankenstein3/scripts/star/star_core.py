    short_exceptions = set(k["short_exceptions"])
    raw = re.findall(r"[a-zA-ZäöüÄÖÜß0-9_-]{2,}", text.lower())
    seen, result = set(), []
    for w in raw:
        if w in seen:
            continue
        if w in stop_words:
            continue
        if len(w) < 4 and w not in short_exceptions:
            continue
        seen.add(w)
        result.append(w)
    return result[:12]


