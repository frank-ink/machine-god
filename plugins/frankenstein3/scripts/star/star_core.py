def _lease_ttl() -> int:
    return int(_config()["leases.ttl_seconds"])


def lease_hold(resource: str, holder: str, generation: int = 1) -> None:
    """Grants/renews a lease on `resource` for `holder`. Overwrites
    a foreign, already expired lease silently (it was free);
    renews own; leaves a foreign, still valid lease standing --
    NOT refused, just not overwritten (the message to the other
    session arises separately via lease_hints(), never by blocking
    here)."""
    try:
        now = _now()
        ttl = _lease_ttl()
        with contextlib.closing(write_connection()) as c:
            available = c.execute(
                "SELECT holder, expires_at FROM leases WHERE resource=?", (resource,)
            ).fetchone()
            if available and available[0] != holder and available[1] > now:
                return  # foreign, still valid lease -- do not overwrite, just do not newly grant
            c.execute(
                "INSERT INTO leases (resource, holder, generation, expires_at, nonce) "
                "VALUES (?,?,?,?,?) "
                "ON CONFLICT(resource) DO UPDATE SET holder=excluded.holder, "
                "generation=excluded.generation, expires_at=excluded.expires_at, "
                "nonce=excluded.nonce",
                (resource, holder, generation, now + ttl, str(uuid.uuid4())),
            )
            c.commit()
    except Exception as e:
        _log(f"lease_hold error resource={resource} holder={holder}: {e}")


def lease_hints(except_session: Optional[str] = None, resources: Optional[list] = None,
                    limit: int = 8) -> list:
    """Reads active (not expired) leases of other sessions. Pure
    notification, no effect -- caller attaches result to SessionStart
    or possibility space. `resources`, if given, filters to exactly
    these paths (e.g. affected files of a handoff capsule);
    otherwise all active foreign leases."""
    try:
        now = _now()
        ttl = _lease_ttl()
        with contextlib.closing(connection()) as c:
            sql = "SELECT resource, holder, expires_at FROM leases WHERE expires_at > ?"
            params: list = [now]
            if except_session:
                sql += " AND holder != ?"
                params.append(except_session)
            if resources:
                placeholder = ",".join("?" * len(resources))
                sql += f" AND resource IN ({placeholder})"
                params.extend(resources)
            sql += " ORDER BY expires_at DESC LIMIT ?"
            params.append(limit)
            lines = c.execute(sql, params).fetchall()
    except Exception as e:
        _log(f"lease_hints error: {e}")
        return []
    hints = []
    for resource, holder, expires_at in lines:
        since_s = max(0, now - (expires_at - ttl))
        since_min = int(since_s // 60)
        hints.append(
            f"{resource} has been in progress for {since_min} min at session {holder}."
        )
    return hints


def _compression_latency_p50() -> dict:
    try:
        with contextlib.closing(connection()) as c:
            values = [json.loads(r[0]).get("wall_ms") for r in c.execute(
                "SELECT prestage_receipt_json FROM mv_prestage_turns "
                "WHERE outcome_ok=1 ORDER BY created_at DESC LIMIT 100"
            ).fetchall()]
        values = sorted(w for w in values if isinstance(w, (int, float)))
    except Exception:
        values = []
    if not values:
        return {"p50_ms": None, "n": 0}
    n = len(values)
    return {"p50_ms": values[n // 2], "p95_ms": values[int(n * 0.95) if n > 1 else 0],
            "max_ms": values[-1], "n": n}


def _instrument_compaction_balance() -> list:
    source = "unified.db mv_prestage_turns (PHASE 15)"
    lines = []
    try:
        with contextlib.closing(connection()) as c:
            c.row_factory = sqlite3.Row
            total = c.execute("SELECT COUNT(*) AS n FROM mv_prestage_turns").fetchone()["n"]
            lines.append(_measurement_line("compaction_balance", source, "runs_total",
                                          float(total), "count", {}))
            for row in c.execute(
                "SELECT prestage_model, COUNT(*) AS n FROM mv_prestage_turns "
                "WHERE prestage_model LIKE 'FAILURE:%' GROUP BY prestage_model"
            ):
                cause = row["prestage_model"].split(":", 1)[1] if ":" in row["prestage_model"] else "unknown"
                lines.append(_measurement_line("compaction_balance", source, f"failure:{cause}",
                                              float(row["n"]), "count",
                                              {"hint": "separated by cause, §0.1.1 -- never mixed"}))
            success = c.execute("SELECT COUNT(*) AS n FROM mv_prestage_turns WHERE outcome_ok=1").fetchone()["n"]
            lines.append(_measurement_line("compaction_balance", source, "successful", float(success),
                                          "count", {}))
            p50 = _compression_latency_p50()
            if p50.get("p50_ms") is not None:
                lines.append(_measurement_line("compaction_balance", source, "p50_ms",
                                              float(p50["p50_ms"]), "ms", p50))
            else:
                lines.append(_measurement_line("compaction_balance", source, "p50_ms", 0.0, "ms",
                                              _measurement_unknown("no successful move yet")))
        return lines
    except Exception as e:
        return [_measurement_line("compaction_balance", source, "connection_error", 0.0, "bool",
                                _measurement_unknown(f"{type(e).__name__}: {e}"))]


def _system_last_read() -> dict:
    """Cheapest possible load measurement -- /proc/loadavg, no subprocesses,
    no library dependencies, <5ms. Basis for overload_protection_check()
    AND for system_health_capture() (load1/load5/load15 columns)."""
    try:
        with open("/proc/loadavg", "r", encoding="utf-8") as f:
            parts = f.read().split()
        load1, load5, load15 = float(parts[0]), float(parts[1]), float(parts[2])
    except Exception as e:
        return {"stand": "UNKNOWN", "reason": f"/proc/loadavg not readable: {e}"}
    cores = os.cpu_count() or 1
    return {
        "stand": "OK", "load1": load1, "load5": load5, "load15": load15,
        "cores": cores, "last_per_core": round(load1 / cores, 4),
    }


def _system_ram_read() -> dict:
    try:
        info = {}
        with open("/proc/meminfo", "r", encoding="utf-8") as f:
            for line in f:
                if ":" not in line:
                    continue
                key, value = line.split(":", 1)
                info[key.strip()] = value.strip()
        total_kb = int(info["MemTotal"].split()[0])
        available_kb = int(info.get("MemAvailable", info.get("MemFree", "0 kB")).split()[0])
        percent = round((1 - available_kb / total_kb) * 100, 1) if total_kb else None
        return {"stand": "OK", "ram_percent": percent, "mem_total_kb": total_kb, "mem_available_kb": available_kb}
    except Exception as e:
        return {"stand": "UNKNOWN", "reason": f"/proc/meminfo not readable: {e}"}


def _system_disk_read(path: str = "/") -> dict:
    try:
        total, used, free = shutil.disk_usage(path)
        percent = round(used / total * 100, 1) if total else None
        return {"stand": "OK", "disk_percent": percent, "disk_total_bytes": total, "disk_free_bytes": free}
    except Exception as e:
        return {"stand": "UNKNOWN", "reason": f"disk_usage({path}) failed: {e}"}


def _system_cpu_percent(interval: float = 0.15) -> dict:
    """Two /proc/stat samples over a short interval -- only called in
    system_health_capture() (manual command/event, NO
    hook path, the 0.15s sleep would not be justifiable in any hook time budget from §1.9.3).
    overload_protection_check() uses load1/core INSTEAD,
    that's exactly why this stays separate."""
    def _read():
        with open("/proc/stat", "r", encoding="utf-8") as f:
            line = f.readline()
        values = [int(x) for x in line.split()[1:]]
        idle = values[3] + (values[4] if len(values) > 4 else 0)
        return idle, sum(values)
    try:
        idle1, total1 = _read()
        time.sleep(interval)
        idle2, total2 = _read()
        d_idle, d_total = idle2 - idle1, total2 - total1
        percent = round((1 - d_idle / d_total) * 100, 1) if d_total else None
        return {"stand": "OK", "cpu_percent": percent}
    except Exception as e:
        return {"stand": "UNKNOWN", "reason": f"/proc/stat not readable: {e}"}


