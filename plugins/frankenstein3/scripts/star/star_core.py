def validate_connection(c: sqlite3.Connection) -> dict:
    """Checks whether the connection has the critical properties."""
    result = {"ok": True, "mode": "unknown", "query_only": None, "busy_timeout": None, "error": []}
    try:
        mode_row = c.execute("PRAGMA journal_mode").fetchone()
        result["mode"] = mode_row[0] if mode_row else "unknown"
        qo_row = c.execute("PRAGMA query_only").fetchone()
        result["query_only"] = qo_row[0] if qo_row else None
        bt_row = c.execute("PRAGMA busy_timeout").fetchone()
        result["busy_timeout"] = bt_row[0] if bt_row else None
        if result["query_only"] != 0:
            result["error"].append(f"query_only={result['query_only']} — expected 0 for write access")
            result["ok"] = False
        if not result["busy_timeout"] or result["busy_timeout"] < 5000:
            result["error"].append(f"busy_timeout={result['busy_timeout']}ms — expected >=5000ms")
            result["ok"] = False
        if result["mode"] not in ("wal", "memory"):
            result["error"].append(f"journal_mode={result['mode']} — expected 'wal' or 'memory'")
            result["ok"] = False
    except sqlite3.Error as e:
        result["error"].append(f"Check failed: {e}")
        result["ok"] = False
    return result


def validate_table_exists(c: sqlite3.Connection, table_name: str) -> bool:
    try:
        result = c.execute(
            "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name=?", (table_name,)
        ).fetchone()
        return result[0] > 0 if result else False
    except sqlite3.Error:
        return False


def validate_db_schema(path: str = _FIRE_LANE_DB_PATH) -> dict:
    result = {"ok": True, "tables": {}, "error": []}
    critical_tables = ["article", "edge", "article_sphere", "wm_topology", "wm_reading", "curation"]
    try:
        c = connection(path)
        for table in critical_tables:
            exists = validate_table_exists(c, table)
            result["tables"][table] = exists
            if not exists:
                result["error"].append(f"Table missing: {table}")
                result["ok"] = False
        c.close()
    except sqlite3.Error as e:
        result["error"].append(f"Schema check failed: {e}")
        result["ok"] = False
    return result


def check_condition(condition: str, context: Optional[dict] = None) -> dict:
    """Accepted conditions: connection_reading / connection_writing / schema_complete."""
    result = {"condition": condition, "ok": False, "details": {}, "error": []}
    try:
        if condition == "connection_reading":
            c = connection()
            result["details"] = validate_connection(c)
            result["ok"] = result["details"]["ok"]
            c.close()
        elif condition == "connection_writing":
            c = write_connection()
            result["details"] = validate_connection(c)
            result["ok"] = result["details"]["ok"]
            c.close()
        elif condition == "schema_complete":
            result["details"] = validate_db_schema()
            result["ok"] = result["details"]["ok"]
        else:
            result["error"].append(f"Unknown condition: {condition}")
    except Exception as e:
        result["error"].append(f"Check failed: {e}")
    return result


