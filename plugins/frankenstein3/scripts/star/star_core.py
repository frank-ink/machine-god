_FILE_LIKE = re.compile(r"^[./~][^\s]*$|^[^\s]+/[^\s]+$|\.[a-zA-Z0-9]{1,6}$")


def _capsule_affected_files(c, session_id: str, target: str) -> list:
    """Deterministic, NO model formulation: everything that looks like a path in --target,
    plus the files actually touched last in this session via Write/Edit/MultiEdit/
    NotebookEdit (effects table, see
    remember())."""
    files = set()
    for tok in re.split(r"[\s,;]+", target or ""):
        tok = tok.strip().strip("`'\"")
        if tok and _FILE_LIKE.search(tok):
            files.add(tok)
    try:
        rows = c.execute(
            "SELECT DISTINCT e.target FROM effects e "
            "LEFT JOIN workspace_episodes w ON e.episode_id = w.episode_id "
            "WHERE w.session_id=? AND e.capability IN ('Write','Edit','MultiEdit','NotebookEdit') "
            "ORDER BY e.ts DESC LIMIT 20",
            (session_id,),
        ).fetchall()
        for (t,) in rows:
            if t:
                files.add(t)
    except Exception as e:
        _log(f"_capsule_affected_files error sid={session_id}: {e}")
    return sorted(files)


def _capsule_open_state(c, session_id: str) -> list:
    """Other not yet completed packages -- what was already running before
    this handoff originated. Deterministic from the table, not invented."""
    try:
        rows = c.execute(
            "SELECT work_package_id, task, stand FROM entityos_work_package "
            "WHERE stand IN ('open','running') ORDER BY changed DESC LIMIT 5"
        ).fetchall()
        return [f"{pid} [{stand}] {_short(on, 100)}" for pid, on, stand in rows]
    except Exception as e:
        _log(f"_capsule_open_state error: {e}")
        return []


def _capsule_relevant_memories(c, task: str, why: str, limit: int = 6) -> list:
    """Keyword-based LIKE search in durable_memory (kind NOT IN ('event','turn_log','stop','session_start')) --
    same mechanism as search()/automatic_recall(), only here for the
    handoff capsule instead of for the chat injection. No ranking by a
    model, only recency + keyword overlap."""
    keywords = _keywords(f"{task} {why}")
    if not keywords:
        return []
    hit = []
    seen = set()
    try:
        for word in keywords[:6]:
            like = f"%{word}%"
            for mem_id, kind, subject, value, ts in c.execute(
                "SELECT memory_id, kind, subject, value, ts FROM durable_memory "
                "WHERE (subject LIKE ? OR value LIKE ?) AND kind NOT IN ('event','turn_log','stop','session_start') "
                "ORDER BY ts DESC LIMIT 4",
                (like, like),
            ):
                if mem_id in seen:
                    continue
                seen.add(mem_id)
                hit.append((ts, f"[{kind}] {subject}: {_short(value, 160)}"))
            if len(hit) >= limit:
                break
    except Exception as e:
        _log(f"_capsule_relevant_memories error: {e}")
    hit.sort(key=lambda p: p[0], reverse=True)
    return [line for _, line in hit[:limit]]


def handoff(session_id: str, task: str, target: str, why: str, topic: str = "") -> dict:
    """ZECP13: creates an entityos_work_package (stand='running') and builds
    the handoff capsule -- composed EXCLUSIVELY from the DB, no
    sentence of it is formulated by the model. This is the text that the
    coordinator passes to the delegated subagent. `star_cli` itself delegates
    NOTHING (explicit non-goal) -- it only records that delegation occurred,
    and gives the coordinator the material for it.

    `topic` (optional, 2026-08-27 addendum topic register): free
    short title under which this undertaking becomes findable in topics_status
    (e.g. 'Xeno/HCU-Trainingscurriculum'). If missing, the key
    falls back to `task` -- still better findable than no row at all,
    see docstring of the topic register section."""
    try:
        with contextlib.closing(write_connection()) as c:
            work_package_id = _uid("work-package")
            now = _now()
            c.execute(
                "INSERT INTO entityos_work_package (work_package_id, orderer, session_id, "
                "task, target, why, stand, result, evidence, created, changed) "
                "VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                (work_package_id, USER_ID, session_id, task, target, why, "running", None, None, now, now),
            )
            c.commit()

            files = _capsule_affected_files(c, session_id, target)
            open_items = _capsule_open_state(c, session_id)
            memories = _capsule_relevant_memories(c, task, why)
    except Exception as e:
        _log(f"handoff error sid={session_id}: {e}")
        return {"work_package_id": None, "capsule": f"handoff failed: {e}"}

    # P5d: Lease on every affected file -- the session that delegates,
    # marks the files from NOW as in progress, not only at the first
    # actual edit (otherwise a second session would see the collision too
    # late). Only NOTIFICATION for others, never a lock for this session.
    hints = []
    if files:
        try:
            with contextlib.closing(connection()) as c2:
                genrow = c2.execute(
                    "SELECT generation FROM sessions WHERE session_id=?", (session_id,)
                ).fetchone()
            generation = genrow[0] if genrow else 1
        except Exception:
            generation = 1
        for path in files:
            lease_hold(path, session_id, generation)
        hints = lease_hints(except_session=session_id, resources=files)

    _room_call_write(session_id, "HANDOFF", f"work_package_id={work_package_id} task={_short(task, 120)}")
    _topics_status_write(topic or task, f"running: {_short(task, 300)}", "running",
                              work_package_id, session_id)

    lines = [
        f"HANDOFF {work_package_id}",
        f"Task: {task}",
    ]
    if target:
        lines.append(f"Wherewith: {target}")
    if why:
        lines.append(f"Why: {why}")
    lines.append(f"Affected files ({len(files)}): " + (", ".join(files) if files else "none determined"))
    if hints:
        lines.append("Collision notice (no lock): " + " | ".join(hints))
    if open_items:
        lines.append(f"Other open packages ({len(open_items)}):")
        lines.extend(f"  - {z}" for z in open_items)
    if memories:
        lines.append(f"Relevant prior knowledge ({len(memories)}):")
        lines.extend(f"  - {z}" for z in memories)
    lines.append(
        f"Evidence duty at completion: `star_cli.py reconcile --work-package-id {work_package_id} "
        f"--result ... --evidence ...` -- evidence MUST be effect:<id>, file:<path>:<sha256> "
        f"or test:<exit_code>:<description>. Without evidence the package is counted as "
        f"failed/unproven_claim, not counted as success."
    )
    return {"work_package_id": work_package_id, "capsule": "\n".join(lines)}


