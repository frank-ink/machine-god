def bug_einstufen(*, dateien: Optional[list] = None, befehl: str = "",
                   projekt_wurzeln: Optional[list] = None) -> dict:
    """PHASE 17 Punkt 3 -- mechanischer Klein/Gross-Klassifikator. KEINE
    Modell-Ermessensentscheidung ueber die Schwere selbst (das Konzeptdokument
    ist hier ausdruecklich: "keine Modell-Ermessensentscheidung ueber die
    Schwere"), reine Musterpruefung. Fail-closed in jede Richtung: kein
    Input -> gross; jeder Treffer in _BUG_GROSS_BEFEHL_MUSTER -> gross; jede
    Datei ausserhalb der Projektwurzeln -> gross. 'klein' ist der einzige
    Zweig, der ALLE Pruefungen bestehen muss."""
    dateien = dateien or []
    wurzeln_roh = projekt_wurzeln or [str(STERN_DIR.parent)]
    wurzeln = []
    for w in wurzeln_roh:
        try:
            wurzeln.append(str(Path(w).resolve()))
        except Exception:
            pass
    gruende = []

    if befehl and _BUG_GROSS_BEFEHL_MUSTER.search(befehl):
        gruende.append("befehl trifft Systemmuster (Paketmanager/Rechte/Dienst/irreversibel/extern)")

    for d in dateien:
        try:
            aufgeloest = str(Path(d).resolve())
        except Exception as e:
            gruende.append(f"pfad nicht aufloesbar: {d} ({e})")
            continue
        innerhalb = any(aufgeloest == w or aufgeloest.startswith(w.rstrip("/") + "/") for w in wurzeln)
        if not innerhalb:
            gruende.append(f"datei ausserhalb Projektwurzel: {d}")

    if not dateien and not befehl:
        gruende.append("weder Dateien noch Befehl angegeben -- nichts zu pruefen, fail-closed")

    if gruende:
        return {"einstufung": "gross", "gruende": gruende}
    return {
        "einstufung": "klein",
        "gruende": ["eigener Code, alle Pfade innerhalb Projektwurzel, kein Systemmuster getroffen"],
    }
