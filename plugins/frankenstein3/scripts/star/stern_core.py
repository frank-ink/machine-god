def _system_bestand_apt() -> list:
    try:
        r = subprocess.run(
            ["dpkg-query", "-W", "-f=${Package}\t${Version}\n"],
            capture_output=True, text=True, timeout=25,
        )
        paare = []
        for zeile in r.stdout.splitlines():
            teile = zeile.split("\t")
            if len(teile) == 2 and teile[0]:
                paare.append((teile[0], teile[1]))
        return paare
    except Exception as e:
        _log(f"system_bestand apt fehler: {e}")
        return []


def _system_bestand_pip() -> list:
    for befehl in ([sys.executable, "-m", "pip", "list", "--format=freeze"],
                    ["pip3", "list", "--format=freeze"], ["pip", "list", "--format=freeze"]):
        try:
            r = subprocess.run(befehl, capture_output=True, text=True, timeout=30)
            if r.returncode == 0 and r.stdout.strip():
                paare = []
                for zeile in r.stdout.splitlines():
                    if "==" in zeile:
                        name, version = zeile.split("==", 1)
                        paare.append((name.strip(), version.strip()))
                return paare
        except Exception:
            continue
    return []


def _system_bestand_npm() -> list:
    try:
        r = subprocess.run(
            ["npm", "-g", "list", "--depth=0", "--json"],
            capture_output=True, text=True, timeout=30,
        )
        d = json.loads(r.stdout or "{}")
        paare = []
        for name, info in (d.get("dependencies") or {}).items():
            paare.append((name, (info or {}).get("version", "")))
        return paare
    except Exception as e:
        _log(f"system_bestand npm fehler: {e}")
        return []


def system_bestand_erfassen() -> dict:
    """PHASE 17 Punkt 1 -- realer Bestand ueber drei echte Subprozess-
    Aufrufe (dpkg-query/pip/npm), NIE vom Modell erfunden. Handbefehl, kein
    Hook-Pfad (dpkg-query allein ist schnell, npm -g list/pip list koennen
    Sekunden brauchen -- zu teuer fuer jedes SessionStart, siehe §1.9.3).
    Tabelle wird bei jedem Lauf VOLLSTAENDIG ersetzt (aktueller Stand, keine
    Historie noetig -- anders als system_gesundheit)."""
    lauf_id = _uid("sysb")
    jetzt = _jetzt()
    kategorien = {"apt": _system_bestand_apt(), "pip": _system_bestand_pip(), "npm": _system_bestand_npm()}
    zeilen = []
    for kategorie, paare in kategorien.items():
        for name, version in paare:
            zeilen.append((_uid("sysb"), lauf_id, jetzt, kategorie, name, version, "subprocess"))
    try:
        with contextlib.closing(schreib_verbindung()) as c:
            _sicherstellen_system_bestand_tabelle(c)
            c.execute("DELETE FROM system_bestand")
            if zeilen:
                c.executemany(
                    "INSERT INTO system_bestand (id, lauf_id, ts, kategorie, name, version, quelle) "
                    "VALUES (?,?,?,?,?,?,?)", zeilen,
                )
            c.commit()
    except Exception as e:
        _log(f"system_bestand_erfassen fehler: {e}")
        return {"stand": "FEHLER", "fehler": str(e)}
    return {
        "stand": "OK", "lauf_id": lauf_id, "ts": jetzt,
        "anzahl": {k: len(v) for k, v in kategorien.items()}, "gesamt": len(zeilen),
    }


def lastschutz_pruefen(*, schwelle_je_kern: float = 1.5) -> dict:
    """PHASE 17 Punkt 2 -- Handbefehl vor dem Spawnen paralleler Bau-Agenten
    (kein Hook, kein Dauerprozess -- reines On-Demand-Lesen von /proc/
    loadavg, <5ms). last_je_kern >= Schwelle -> 'drosseln', sonst 'ok'.
    Unlesbare Last gilt als 'drosseln' (fail-closed, nicht optimistisch)."""
    last = _system_last_lesen()
    if last.get("stand") != "OK":
        return {"stand": "UNBEKANNT", "empfehlung": "drosseln", "grund": last.get("grund", "last nicht lesbar")}
    last_je_kern = last["last_je_kern"]
    empfehlung = "drosseln" if last_je_kern >= schwelle_je_kern else "ok"
    return {
        "stand": "OK", "empfehlung": empfehlung, "load1": last["load1"], "load5": last["load5"],
        "load15": last["load15"], "kerne": last["kerne"], "last_je_kern": last_je_kern,
        "schwelle_je_kern": schwelle_je_kern,
    }


# Mechanisches Klein/Gross-Muster fuer bug_einstufen() -- Paketmanager,
# Rechte-/Benutzerverwaltung, Dienst-Steuerung, Fernausfuehrung, erzwungene
