# ⚠️ WARUM INSTRUMENT 1 SICH AENDERT (Abweichung, im Ruecklauf vermerkt):
# Vor P1 pruefte Instrument 1 fuenf SEPARATE Modulimporte
# (udb.abruf.{paket,moeglichkeitsraum,wegehierarchie,feuerschneise,zustand}).
# Nach P1 SIND vier davon kein eigenes Modul mehr -- sie sind Abschnitte in
# genau dieser Datei (das ist der ganze Punkt von P1: ein Ding, das gebaut
# wurde, hat alle seine Teile dabei). Ein importlib.import_module() auf
# "udb.abruf.wegehierarchie" wuerde jetzt IMMER "FEHLT" melden, obwohl die
# Faehigkeit selbst voll funktionsfaehig im laufenden Prozess steckt --
# das waere kein ehrlicher Regressionsbefund, sondern ein Messfehler DIESES
# Instruments, das seine eigene Grundannahme (getrennte Module) nicht mehr
# stimmt. Deshalb: fuer die vier inline-gewordenen Abschnitte wird jetzt
# geprueft, ob die jeweilige Kernfunktion im laufenden Modul EXISTIERT und
# AUFRUFBAR ist (das ist die einzige Weise, wie sie noch "fehlen" koennten --
# z.B. ein Tippfehler beim Konsolidieren). Fuer paket.py (einzig verbliebenes
# ECHTES externes Modul, §1.7) bleibt der frische importlib-Check exakt wie
# vorher -- das ist weiterhin der reale Risikofall (fehlender Import wie am
# 25.08.). "was"-Bezeichner bleiben unveraendert (import:<modul>) fuer
# Vergleichbarkeit mit der P0-Baseline.
# ═══════════════════════════════════════════════════════════════════════
def _messung_unbekannt(grund: str) -> dict:
    return {"stand": "UNBEKANNT", "grund": grund}


def _messung_zeile(bauteil: str, quelle: str, was: str, wert: float, einheit: str, roh: dict) -> dict:
    roh_json = json.dumps(roh, ensure_ascii=False, sort_keys=True, default=str)
    zeit = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    return {
        "id": str(uuid.uuid4()),
        "bauteil": bauteil,
        "quelle": quelle,
        "zeile_hash": hashlib.sha256(f"{bauteil}|{was}|{zeit}|{roh_json}".encode("utf-8")).hexdigest()[:16],
        "was": was,
        "wert": float(wert),
        "einheit": einheit,
        "zeit": zeit,
        "wirt": "local",
        "instanz": USER_ID,
        "roh": roh_json,
    }


def _instrument_importgesundheit() -> list:
    zeilen = []
    # 1) echte externe Module, echter frischer Import -- wie vor P1. paket
    # UND wegehierarchie bleiben beide echte Dateien (siehe Importblock am
    # Kopf dieser Datei fuer die Begruendung, warum wegehierarchie NICHT
    # inline gehen durfte -- gefunden ueber genau dieses Instrument beim
    # ersten selbsttest-Lauf dieser Phase).
    for modul in ("paket", "wegehierarchie"):
        pfad = f"udb.abruf.{modul}"
        try:
            importlib.import_module(pfad)
            zeilen.append(_messung_zeile(
                "importgesundheit", pfad, f"import:{modul}", 1.0, "bool",
                {"modul": modul, "stand": "OK"},
            ))
        except Exception as e:
            zeilen.append(_messung_zeile(
                "importgesundheit", pfad, f"import:{modul}", 0.0, "bool",
                {"modul": modul, "stand": f"FEHLT:{type(e).__name__}: {e}"},
            ))
    # 2) drei inline gewordene Abschnitte -- Existenz/Aufrufbarkeit im
    # laufenden Modul statt eines (nicht mehr zutreffenden) Fremdimports.
    inline_pruefungen = {
        "moeglichkeitsraum": moeglichkeitsraum,
        "feuerschneise": pruefe_kondition,
        "zustand": verbindung,
    }
    for modul, funktion in inline_pruefungen.items():
        ok = callable(funktion)
        zeilen.append(_messung_zeile(
            "importgesundheit", f"stern.py (inline seit P1, ehem. udb.abruf.{modul})",
            f"import:{modul}", 1.0 if ok else 0.0, "bool",
            {
                "modul": modul,
                "stand": "OK" if ok else "FEHLT:AttributeError: Funktion nicht auffindbar",
                "hinweis": "seit Phase 1 kein eigenes Modul mehr, siehe Docstring dieses Abschnitts",
            },
        ))
    # 3) PHASE 13 Querverweis P0 -- daten/*.json und daten/sebukku.txt sind
    # keine optionale Zierde: fehlende oder kaputte Tondateien sind ein
    # MESSFEHLSCHLAG, kein stiller Rueckfall auf einen Codestring. persona.md
    # ist selbst schon UNBEKANNT statt OK, wenn leer -- siehe _persona_text().
    _tondateien_pruefungen = (
        ("persona.md", lambda t: len(t.strip()) > 0),
        # Titel im Bild ist letter-spaced ("S E B U K K U"), deshalb Pruefung
        # auf den Leerzeichen entfernten Text statt auf den wortgleichen String.
        ("sebukku.txt", lambda t: "SEBUKKU" in t.replace(" ", "")),
        ("begruessungen.json", lambda t: isinstance(json.loads(t).get("ausweichen"), list)
                                          and len(json.loads(t)["ausweichen"]) > 0),
    )
    for dateiname, pruefung in _tondateien_pruefungen:
        pfad = STERN_DIR / "daten" / dateiname
        try:
            text = pfad.read_text(encoding="utf-8")
            ok = bool(pruefung(text))
            zeilen.append(_messung_zeile(
                "importgesundheit", str(pfad), f"tondatei:{dateiname}", 1.0 if ok else 0.0, "bool",
                {"dateiname": dateiname, "stand": "OK" if ok else "KAPUTT:Inhaltspruefung fehlgeschlagen"},
            ))
        except Exception as e:
            zeilen.append(_messung_zeile(
                "importgesundheit", str(pfad), f"tondatei:{dateiname}", 0.0, "bool",
                {"dateiname": dateiname, "stand": f"FEHLT:{type(e).__name__}: {e}"},
            ))
    return zeilen


_MESSUNG_DAUER_RE = re.compile(r"dauer event=(\S+) (\d+)ms")


def _instrument_hook_latenz() -> list:
    quelle = "hook.log (stern.py:_log 'dauer event=...')"
    try:
        text = LOG.read_text(encoding="utf-8", errors="replace")
    except Exception as e:
        return [_messung_zeile("hook_latenz", quelle, "lesefehler", 0.0, "bool",
                                _messung_unbekannt(f"{type(e).__name__}: {e}"))]

    je_event: dict = {}
    for zeile in text.splitlines():
        m = _MESSUNG_DAUER_RE.search(zeile)
        if m:
            je_event.setdefault(m.group(1), []).append(int(m.group(2)))

    if not je_event:
        return [_messung_zeile("hook_latenz", quelle, "keine_dauerzeilen", 0.0, "bool",
                                _messung_unbekannt("hook.log enthaelt keine 'dauer event='-Zeilen"))]

    k = _konfig()
    limits = {
        "SessionStart": k["limit.SessionStart"], "PreToolUse": k["limit.PreToolUse"],
        "PostToolUse": k["limit.PostToolUse"],
        "Stop": k["limit.Stop"], "SessionEnd": k["limit.SessionEnd"],
        "UserPromptSubmit": k["limit.UserPromptSubmit"],
    }
    standard_limit = k["limit.standard"]

    zeilen = []
    for event, werte in sorted(je_event.items()):
        werte_sortiert = sorted(werte)
        n = len(werte_sortiert)
        p50 = werte_sortiert[int(0.50 * (n - 1))]
        p95 = werte_sortiert[int(0.95 * (n - 1))]
        maxi = werte_sortiert[-1]
        budget_s = limits.get(event, standard_limit)
        budget_ms = budget_s * 1000 if budget_s is not None else None
        zeilen.append(_messung_zeile(
            "hook_latenz", quelle, f"latenz:{event}", float(p50), "ms",
            {
                "event": event, "n": n, "p50_ms": p50, "p95_ms": p95, "max_ms": maxi,
                "budget_ms": budget_ms,
                "unter_budget": (maxi <= budget_ms) if budget_ms is not None else None,
            },
        ))
    return zeilen


