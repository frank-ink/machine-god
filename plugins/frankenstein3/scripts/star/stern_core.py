#      themen_status genau wie gegen durable_memory/entityos_projekte/etc.
#      -- kein zweiter Mechanismus, nur ein zusaetzlicher Suchblock im
#      bestehenden. Kein LLM-Aufruf in einem Hook (§1.9.2 unveraendert):
#      die Stichwortsuche ist reines SQL/LIKE, wie alles andere dort schon.
#
# `thema` ist FREITEXT vom aufrufenden Koordinator (der bereits laufenden
# LLM-Instanz, die handoff()/reconcile() explizit aufruft -- kein Hook,
# keine automatische Generierung). Fehlt --thema, faellt es auf den
# `auftrag`-Text zurueck (deterministisch, nicht erfunden) -- damit auch
# alte/fremde Aufrufer ohne --thema weiterhin eine (dann grobkoernigere)
# Themen-Zeile bekommen, statt ganz zu fehlen. Schluessel ist eine
# normalisierte Kurzform (fuer Dedup/Ueberschreiben), Anzeige bleibt der
# Originaltext.
# ═══════════════════════════════════════════════════════════════════════
def _sicherstellen_themen_status_tabelle(c) -> None:
    c.execute(
        "CREATE TABLE IF NOT EXISTS themen_status("
        "thema_key TEXT PRIMARY KEY, thema TEXT NOT NULL, status_text TEXT NOT NULL, "
        "stand TEXT NOT NULL, paket_id TEXT, session_id TEXT, aktualisiert REAL NOT NULL)"
    )


def _thema_schluessel(thema: str) -> str:
    """Normalisierte Dedup-Kurzform: klein, Whitespace zusammengezogen,
    auf 80 Zeichen gekappt -- derselbe Text (z.B. derselbe `auftrag`) ergibt
    bei handoff() und reconcile() denselben Schluessel, OHNE eine zweite
    paket_id->thema-Zuordnungstabelle zu brauchen."""
    return re.sub(r"\s+", " ", (thema or "").strip().lower())[:80]


def _themen_status_schreiben(thema: str, status_text: str, stand: str,
                              paket_id: Optional[str], session_id: Optional[str]) -> None:
    """Upsert: EINE Zeile je Thema, immer der neueste Stand. Fail-silent
    wie ueberall in diesem Haus."""
    thema = (thema or "").strip()
    if not thema:
        return
    schluessel = _thema_schluessel(thema)
    if not schluessel:
        return
    try:
        with contextlib.closing(schreib_verbindung()) as c:
            _sicherstellen_themen_status_tabelle(c)
            c.execute(
                "INSERT INTO themen_status (thema_key, thema, status_text, stand, paket_id, "
                "session_id, aktualisiert) VALUES (?,?,?,?,?,?,?) "
                "ON CONFLICT(thema_key) DO UPDATE SET thema=excluded.thema, "
                "status_text=excluded.status_text, stand=excluded.stand, "
                "paket_id=excluded.paket_id, session_id=excluded.session_id, "
                "aktualisiert=excluded.aktualisiert",
                (schluessel, _kurz(thema, 120), _kurz(status_text, 400), stand,
                 paket_id, session_id, _jetzt()),
            )
            c.commit()
    except Exception as e:
        _log(f"themen_status_schreiben fehler thema={thema!r}: {e}")


def themen_status_suchen(begriff: Optional[str] = None, limit: int = 8) -> list:
    """Manuelle/programmatische Abfrage (`stern.py thema-status`) -- dieselbe
    Tabelle, die automatischer_abruf()/start_anzeige() auch lesen, nur ohne
    Stichwortzerlegung: EIN Begriff (oder keiner = alles), neueste zuerst."""
    zeilen = []
    try:
        with contextlib.closing(verbindung()) as c:
            if begriff and begriff.strip():
                like = f"%{begriff.strip()}%"
                cur = c.execute(
                    "SELECT thema, status_text, stand, aktualisiert, session_id FROM themen_status "
                    "WHERE thema LIKE ? OR status_text LIKE ? ORDER BY aktualisiert DESC LIMIT ?",
                    (like, like, limit),
                )
            else:
                cur = c.execute(
                    "SELECT thema, status_text, stand, aktualisiert, session_id FROM themen_status "
                    "ORDER BY aktualisiert DESC LIMIT ?", (limit,),
                )
            for thema, status_text, stand, aktualisiert, session_id in cur:
                zeilen.append({"thema": thema, "status_text": status_text, "stand": stand,
                                "aktualisiert": aktualisiert, "session_id": session_id})
    except sqlite3.OperationalError:
        pass  # Tabelle existiert noch nicht -- vor dem ersten handoff/reconcile mit --thema normal
    except Exception as e:
        _log(f"themen_status_suchen fehler begriff={begriff!r}: {e}")
    return zeilen


