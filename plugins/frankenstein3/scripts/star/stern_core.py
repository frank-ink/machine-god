def _instrument_tabellenfuellstand() -> list:
    quelle = "unified.db sqlite_master + COUNT(*) je Tabelle"
    try:
        with contextlib.closing(verbindung()) as c:
            vorhanden = {r[0] for r in c.execute(
                "SELECT name FROM sqlite_master WHERE type IN ('table','view')"
            ).fetchall()}
            zeilen = []
            for tabelle in _MESSUNG_KANONISCHE_TABELLEN:
                if tabelle not in vorhanden:
                    zeilen.append(_messung_zeile(
                        "tabellenfuellstand", quelle, f"zeilen:{tabelle}", 0.0, "anzahl",
                        {"tabelle": tabelle, "stand": "LEER_WEIL_TABELLE_FEHLT"},
                    ))
                    continue
                try:
                    n = c.execute(f'SELECT COUNT(*) FROM "{tabelle}"').fetchone()[0]
                except Exception as e:
                    zeilen.append(_messung_zeile(
                        "tabellenfuellstand", quelle, f"zeilen:{tabelle}", 0.0, "anzahl",
                        _messung_unbekannt(f"{type(e).__name__}: {e}"),
                    ))
                    continue
                stand = "GEFUELLT" if n > 0 else "LEER_WEIL_NIE_GESCHRIEBEN"
                zeilen.append(_messung_zeile(
                    "tabellenfuellstand", quelle, f"zeilen:{tabelle}", float(n), "anzahl",
                    {"tabelle": tabelle, "stand": stand},
                ))
            return zeilen
    except Exception as e:
        return [_messung_zeile("tabellenfuellstand", quelle, "verbindungsfehler", 0.0, "bool",
                                _messung_unbekannt(f"{type(e).__name__}: {e}"))]


def _instrument_digest_frische() -> list:
    """Instrument 6 -- seit P1 aus star_digest_lauf statt aus der mtime von
    forschung-digest.json (die Datei entfaellt, 1c)."""
    quelle = "star_digest_lauf.generated_at (statt frueher forschung-digest.json mtime)"
    intervall_min = 45.0
    schwelle_min = 3 * intervall_min
    try:
        with contextlib.closing(verbindung()) as c:
            row = c.execute(
                "SELECT generated_at FROM star_digest_lauf ORDER BY generated_at DESC LIMIT 1"
            ).fetchone()
    except Exception as e:
        return [_messung_zeile("digest_frische", quelle, "alter_min", 0.0, "min",
                                _messung_unbekannt(f"{type(e).__name__}: {e}"))]
    if not row or not row[0]:
        return [_messung_zeile("digest_frische", quelle, "alter_min", 0.0, "min",
                                _messung_unbekannt("star_digest_lauf ist leer -- noch kein Lauf verzeichnet"))]
    try:
        dt = datetime.strptime(row[0], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
        alter_min = (datetime.now(timezone.utc) - dt).total_seconds() / 60.0
    except Exception as e:
        return [_messung_zeile("digest_frische", quelle, "alter_min", 0.0, "min",
                                _messung_unbekannt(f"Zeitformat unlesbar: {e}"))]
    stand = "VERALTET" if alter_min >= schwelle_min else "FRISCH"
    return [_messung_zeile(
        "digest_frische", quelle, "alter_min", alter_min, "min",
        {"alter_min": round(alter_min, 1), "intervall_min": intervall_min,
         "schwelle_veraltet_min": schwelle_min, "stand": stand},
    )]


def messen() -> dict:
    """PHASE 0 -- der eine Befehl (`stern.py messen`). Handbefehl -- wird von
    KEINEM Hook automatisch aufgerufen."""
    start = time.monotonic()
    alle_zeilen: list = []
    fehler_je_instrument: dict = {}

    for name, funktion in (
        ("importgesundheit", _instrument_importgesundheit),
        ("hook_latenz", _instrument_hook_latenz),
        ("abruf_ausbeute", _instrument_abruf_ausbeute),
        # "wegehierarchie"-Instrument PHASE 4 entfernt (GLEICHVERTEILT-Verdikt,
        # siehe Kommentar vor pruefen()) -- kein Ersatz, ersatzlos.
        ("tabellenfuellstand", _instrument_tabellenfuellstand),
        ("digest_frische", _instrument_digest_frische),
        ("sicht_bilanz", _instrument_sicht_bilanz),  # PHASE 14/14d, siebtes Instrument
        ("verdichtungsbilanz", _instrument_verdichtungsbilanz),  # PHASE 15/15.5.1, achtes Instrument
    ):
        try:
            alle_zeilen.extend(funktion())
        except Exception as e:
            fehler_je_instrument[name] = f"{type(e).__name__}: {e}"
            _log(f"messen instrument={name} fehler: {e}")

    lauf_id = str(uuid.uuid4())
    try:
        with contextlib.closing(schreib_verbindung()) as c:
            for z in alle_zeilen:
                c.execute(
                    "INSERT INTO messung (id, bauteil, quelle, zeile_hash, was, wert, einheit, "
                    "zeit, wirt, instanz, roh) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                    (z["id"], z["bauteil"], z["quelle"], z["zeile_hash"], z["was"], z["wert"],
                     z["einheit"], z["zeit"], z["wirt"], z["instanz"], z["roh"]),
                )
            meta = {
                "letzter_lauf_id": lauf_id,
                "letzter_lauf_zeit": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "letzter_lauf_zeilen": str(len(alle_zeilen)),
                "letzter_lauf_dauer_s": str(round(time.monotonic() - start, 3)),
                "letzter_lauf_fehler_je_instrument": json.dumps(fehler_je_instrument, ensure_ascii=False),
            }
            for k, v in meta.items():
                c.execute(
                    "INSERT INTO messung_meta (key, value) VALUES (?, ?) "
                    "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                    (k, v),
                )
            c.commit()
    except Exception as e:
        _log(f"messen schreiben fehlgeschlagen: {e}")
        return {"stand": "FEHLER", "fehler": str(e), "zeilen_geplant": len(alle_zeilen)}

    return {
        "stand": "OK",
        "lauf_id": lauf_id,
        "zeilen": len(alle_zeilen),
        "dauer_s": round(time.monotonic() - start, 3),
        "fehler_je_instrument": fehler_je_instrument,
    }


