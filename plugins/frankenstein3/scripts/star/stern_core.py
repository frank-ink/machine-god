# ABSCHNITT: LEASES (P5d) -- KollisionsMELDUNG, keine KollisionsSPERRE.
# Harte Grenze 4 (§1.9): kein Hook blockiert je eine Sitzung. `leases`
# vergibt eine Pacht auf einen Ressourcenpfad (i.d.R. Dateipfad), wenn eine
# Sitzung ihn per Write/Edit/MultiEdit/NotebookEdit anfasst (verdrahtet in
# merken()), und andere Sitzungen erfahren davon rein informativ -- bei
# SessionStart und im Moeglichkeitsraum (nie als Abbruch, nie als Fehler).
#
# "seit wann" wird NICHT als eigene Spalte gefuehrt (Schema ist fix:
# resource, holder, generation, expires_at, nonce -- keine issued_at-Spalte).
# Stattdessen: issued_at = expires_at - ttl, rekonstruiert aus der bekannten
# TTL-Konstante zum Meldezeitpunkt. Das ist exakt, SOLANGE die TTL zwischen
# Vergabe und Abfrage nicht per Hand in star_konfig geaendert wurde -- bei
# einer Aenderung waere die rekonstruierte Zeit ungenau, aber nie falsch in
# eine Richtung, die eine Sperre vortaeuscht (nur die Minutenangabe der
# Meldung koennte driften). Kein Erfinden einer Spalte ausserhalb des im
# Auftrag genannten, bereits bestehenden Schemas.
# ═══════════════════════════════════════════════════════════════════════
def _lease_ttl() -> int:
    return int(_konfig()["leases.ttl_sekunden"])


def lease_halten(resource: str, holder: str, generation: int = 1) -> None:
    """Vergibt/erneuert eine Pacht auf `resource` fuer `holder`. Ueberschreibt
    eine fremde, bereits abgelaufene Pacht kommentarlos (sie war frei);
    erneuert die eigene; laesst eine fremde, noch gueltige Pacht stehen --
    NICHT verweigert, nur nicht ueberschrieben (die Meldung an die andere
    Sitzung entsteht separat ueber lease_hinweise(), nie durch Blockieren
    hier)."""
    try:
        jetzt = _jetzt()
        ttl = _lease_ttl()
        with contextlib.closing(schreib_verbindung()) as c:
            vorhanden = c.execute(
                "SELECT holder, expires_at FROM leases WHERE resource=?", (resource,)
            ).fetchone()
            if vorhanden and vorhanden[0] != holder and vorhanden[1] > jetzt:
                return  # fremde, noch gueltige Pacht -- nicht ueberschreiben, nur nicht neu vergeben
            c.execute(
                "INSERT INTO leases (resource, holder, generation, expires_at, nonce) "
                "VALUES (?,?,?,?,?) "
                "ON CONFLICT(resource) DO UPDATE SET holder=excluded.holder, "
                "generation=excluded.generation, expires_at=excluded.expires_at, "
                "nonce=excluded.nonce",
                (resource, holder, generation, jetzt + ttl, str(uuid.uuid4())),
            )
            c.commit()
    except Exception as e:
        _log(f"lease_halten fehler resource={resource} holder={holder}: {e}")


def lease_hinweise(ausser_sitzung: Optional[str] = None, ressourcen: Optional[list] = None,
                    limit: int = 8) -> list:
    """Liest aktive (nicht abgelaufene) Pachten anderer Sitzungen. Reine
    Meldung, keine Wirkung -- Aufrufer haengt das Ergebnis an SessionStart
    oder Moeglichkeitsraum an. `ressourcen`, falls gegeben, filtert auf genau
    diese Pfade (z.B. die betroffenen Dateien einer Handoff-Kapsel);
    andernfalls alle aktiven fremden Pachten."""
    try:
        jetzt = _jetzt()
        ttl = _lease_ttl()
        with contextlib.closing(verbindung()) as c:
            sql = "SELECT resource, holder, expires_at FROM leases WHERE expires_at > ?"
            params: list = [jetzt]
            if ausser_sitzung:
                sql += " AND holder != ?"
                params.append(ausser_sitzung)
            if ressourcen:
                platzhalter = ",".join("?" * len(ressourcen))
                sql += f" AND resource IN ({platzhalter})"
                params.extend(ressourcen)
            sql += " ORDER BY expires_at DESC LIMIT ?"
            params.append(limit)
            zeilen = c.execute(sql, params).fetchall()
    except Exception as e:
        _log(f"lease_hinweise fehler: {e}")
        return []
    hinweise = []
    for resource, holder, expires_at in zeilen:
        seit_s = max(0, jetzt - (expires_at - ttl))
        seit_min = int(seit_s // 60)
        hinweise.append(
            f"{resource} ist seit {seit_min} min bei Sitzung {holder} in Arbeit."
        )
    return hinweise


def _verdichtung_latenz_p50() -> dict:
    try:
        with contextlib.closing(verbindung()) as c:
            werte = [json.loads(r[0]).get("wall_ms") for r in c.execute(
                "SELECT prestage_receipt_json FROM mv_prestage_turns "
                "WHERE outcome_ok=1 ORDER BY created_at DESC LIMIT 100"
            ).fetchall()]
        werte = sorted(w for w in werte if isinstance(w, (int, float)))
    except Exception:
        werte = []
    if not werte:
        return {"p50_ms": None, "n": 0}
    n = len(werte)
    return {"p50_ms": werte[n // 2], "p95_ms": werte[int(n * 0.95) if n > 1 else 0],
            "max_ms": werte[-1], "n": n}


