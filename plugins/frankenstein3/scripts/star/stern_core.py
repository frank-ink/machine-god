def _system_last_lesen() -> dict:
    """Billigste moegliche Lastmessung -- /proc/loadavg, keine Subprozesse,
    keine Bibliotheksabhaengigkeit, <5ms. Basis fuer lastschutz_pruefen()
    UND fuer system_gesundheit_erfassen() (load1/load5/load15-Spalten)."""
    try:
        with open("/proc/loadavg", "r", encoding="utf-8") as f:
            teile = f.read().split()
        load1, load5, load15 = float(teile[0]), float(teile[1]), float(teile[2])
    except Exception as e:
        return {"stand": "UNBEKANNT", "grund": f"/proc/loadavg nicht lesbar: {e}"}
    kerne = os.cpu_count() or 1
    return {
        "stand": "OK", "load1": load1, "load5": load5, "load15": load15,
        "kerne": kerne, "last_je_kern": round(load1 / kerne, 4),
    }


def _system_ram_lesen() -> dict:
    try:
        info = {}
        with open("/proc/meminfo", "r", encoding="utf-8") as f:
            for zeile in f:
                if ":" not in zeile:
                    continue
                schluessel, wert = zeile.split(":", 1)
                info[schluessel.strip()] = wert.strip()
        total_kb = int(info["MemTotal"].split()[0])
        verfuegbar_kb = int(info.get("MemAvailable", info.get("MemFree", "0 kB")).split()[0])
        prozent = round((1 - verfuegbar_kb / total_kb) * 100, 1) if total_kb else None
        return {"stand": "OK", "ram_prozent": prozent, "mem_total_kb": total_kb, "mem_verfuegbar_kb": verfuegbar_kb}
    except Exception as e:
        return {"stand": "UNBEKANNT", "grund": f"/proc/meminfo nicht lesbar: {e}"}


def _system_disk_lesen(pfad: str = "/") -> dict:
    try:
        gesamt, benutzt, frei = shutil.disk_usage(pfad)
        prozent = round(benutzt / gesamt * 100, 1) if gesamt else None
        return {"stand": "OK", "disk_prozent": prozent, "disk_gesamt_bytes": gesamt, "disk_frei_bytes": frei}
    except Exception as e:
        return {"stand": "UNBEKANNT", "grund": f"disk_usage({pfad}) fehlgeschlagen: {e}"}


def _system_cpu_prozent(intervall: float = 0.15) -> dict:
    """Zwei /proc/stat-Samples ueber ein kurzes Intervall -- nur in
    system_gesundheit_erfassen() aufgerufen (Handbefehl/Event, KEIN
    Hook-Pfad, das 0.15s-Sleep waere in keinem Hook-Zeitbudget aus §1.9.3
    vertretbar). lastschutz_pruefen() nutzt STATTDESSEN load1/Kern,
    genau deshalb bleibt das getrennt."""
    def _lesen():
        with open("/proc/stat", "r", encoding="utf-8") as f:
            zeile = f.readline()
        werte = [int(x) for x in zeile.split()[1:]]
        idle = werte[3] + (werte[4] if len(werte) > 4 else 0)
        return idle, sum(werte)
    try:
        idle1, total1 = _lesen()
        time.sleep(intervall)
        idle2, total2 = _lesen()
        d_idle, d_total = idle2 - idle1, total2 - total1
        prozent = round((1 - d_idle / d_total) * 100, 1) if d_total else None
        return {"stand": "OK", "cpu_prozent": prozent}
    except Exception as e:
        return {"stand": "UNBEKANNT", "grund": f"/proc/stat nicht lesbar: {e}"}


