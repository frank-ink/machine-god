#!/usr/bin/env python3
"""gif2term.py -- Machine God GIF -> braille terminal frames for the welcome screen (replaces Ferris).
Each cell = 2x4 braille dots; per-cell color class: '.' none, 'g' gray, 'w' light, 'r' red, 'R' bright red.
Usage: gif2term.py GIF OUT.rs [--preview]   (deterministic: same GIF -> same .rs)"""
import sys
from PIL import Image, ImageSequence

CROP = (95, 0, 528, 470)  # figure, halo and gate; crowd and outer towers cut (623x623 source)
THR_PCT = 0.55  # dots lit above this brightness percentile
SIZES = {"LARGE": (40, 20), "SMALL": (24, 12)}  # (cols, rows)
DOT = ((0, 0, 0x01), (0, 1, 0x02), (0, 2, 0x04), (1, 0, 0x08), (1, 1, 0x10), (1, 2, 0x20), (0, 3, 0x40), (1, 3, 0x80))


def render(frame, cols, rows):
    w, h = cols * 2, rows * 4
    rgb = frame.convert("RGB").crop(CROP).resize((w, h), Image.BOX)  # BOX keeps thin strokes as mean brightness
    px = rgb.load()
    lum = sorted(max(p) for p in rgb.getdata())
    thr = max(14, lum[int(len(lum) * THR_PCT)])
    lines, colors = [], []
    for cy in range(rows):
        line, col = [], []
        for cx in range(cols):
            bits, lit = 0, []
            for dx, dy, b in DOT:
                r, g, bl = px[cx * 2 + dx, cy * 4 + dy]
                if max(r, g, bl) > thr:
                    bits |= b
                    lit.append((r, g, bl))
            line.append(chr(0x2800 + bits) if bits else " ")
            if not lit:
                col.append(".")
                continue
            r = sum(p[0] for p in lit) / len(lit); g = sum(p[1] for p in lit) / len(lit)
            if r > 1.5 * g + 8:
                col.append("R" if r > 110 else "r")
            else:
                col.append("w" if r > 70 else "g")
        lines.append("".join(line))
        colors.append("".join(col))
    return lines, colors


def main():
    gif, out = sys.argv[1], sys.argv[2]
    frames = [f.copy() for f in ImageSequence.Iterator(Image.open(gif))]
    dur = Image.open(gif).info.get("duration", 450)
    rs = ["//! Machine God welcome motif (generated by design/gif2term.py from the Machine God GIF; do not edit by hand).",
          "//! Braille frames plus a same-shaped color mask: '.' none, 'g' gray, 'w' light, 'r' red, 'R' bright red.", "",
          f"pub(crate) const FRAME_MS: u64 = {dur};", f"pub(crate) const FRAME_COUNT: usize = {len(frames)};", ""]
    for name, (cols, rows) in SIZES.items():
        art, mask = [], []
        for f in frames:
            a, m = render(f, cols, rows)
            art.append(a); mask.append(m)
            if "--preview" in sys.argv and name == "LARGE":
                print("\n".join(a)); print("-" * cols)
        rs.append(f"pub(crate) const {name}_COLS: usize = {cols};")
        rs.append(f"pub(crate) const {name}_ART: [[&str; {rows}]; {len(frames)}] = [")
        for a in art:
            rs.append("    [" + ", ".join('"' + l + '"' for l in a) + "],")
        rs.append("];")
        rs.append(f"pub(crate) const {name}_MASK: [[&str; {rows}]; {len(frames)}] = [")
        for m in mask:
            rs.append("    [" + ", ".join('"' + l + '"' for l in m) + "],")
        rs.append("];\n")
    open(out, "w").write("\n".join(rs))


if __name__ == "__main__":
    main()
